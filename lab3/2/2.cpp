#include <iostream>  // Ввод и вывод
#include <cmath>     // Математические функции
using namespace std;

int main() {
    int a, b;  // Два целых числа

    // Вводим числа
    cout << "Введите первое число: ";
    cin >> a;

    cout << "Введите второе число: ";
    cin >> b;

    // Считаем сумму, разность и произведение
    cout << "Сумма: " << a + b << endl;
    cout << "Разность: " << a - b << endl;
    cout << "Произведение: " << a * b << endl;

    // Проверяем, что делитель не равен нулю
    if (b != 0) {
        cout << "Целочисленное деление: " << a / b << endl;
        cout << "Остаток от деления: " << a % b << endl;
    } else {
        cout << "На ноль делить нельзя" << endl;
    }

    // Возводим первое число в степень второго
    cout << "Степень: " << pow(a, b) << endl;

    return 0;
}