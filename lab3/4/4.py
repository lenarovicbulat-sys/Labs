# Вводим строку
text = input("Введите строку: ")

# Находим длину строки
print("Длина строки:", len(text))

# Переводим строку в верхний и нижний регистр
print("Верхний регистр:", text.upper())
print("Нижний регистр:", text.lower())

# Проверяем, что строка не пустая
if len(text) > 0:
    # Выводим первый и последний символы
    print("Первый символ:", text[0])
    print("Последний символ:", text[-1])
else:
    print("Строка пустая")

# Считаем количество пробелов
print("Количество пробелов:", text.count(" "))