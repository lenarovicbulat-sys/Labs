# Вводим целое число
number = int(input("Введите целое число: "))

# Вводим дробное число
decimal = float(input("Введите дробное число: "))

# Вводим строку
text = input("Введите строку: ")

# Выводим значения и их типы
print("Число:", number)
print("Тип числа:", type(number))

print("Дробное число:", decimal)
print("Тип дробного числа:", type(decimal))

print("Строка:", text)
print("Тип строки:", type(text))