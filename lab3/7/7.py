# Вводим радиус цилиндра
radius = float(input("Введите радиус цилиндра: "))

# Вводим высоту цилиндра
height = float(input("Введите высоту цилиндра: "))

# Проверяем, что значения положительные
if radius <= 0 or height <= 0:
    print("Ошибка: радиус и высота должны быть больше нуля")

else:
    # Задаём приближённое значение числа Пи
    pi = 3.14159

    # Вычисляем объём цилиндра
    volume = pi * radius * radius * height

    # Вычисляем площадь полной поверхности
    surface = 2 * pi * radius * (radius + height)

    # Выводим результаты
    print("Объём цилиндра:", volume)
    print("Площадь поверхности:", surface)